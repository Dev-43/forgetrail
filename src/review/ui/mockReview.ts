import * as vscode from 'vscode';
import { ReviewPresenter, ReviewRequest } from '../../shared/contracts';

/**
 * Registers the 'ForgeTrail: Mock review' command.
 * Allows independent UI testing by presenting 3 sequential ReviewRequests:
 * - 2 replace hunks in the active file
 * - 1 create hunk creating a new file
 */
export function registerMockReview(context: vscode.ExtensionContext, presenter: ReviewPresenter): void {
  const disposable = vscode.commands.registerCommand('forgetrail.mockReview', async () => {
    const editor = vscode.window.activeTextEditor;
    let targetPath = 'src/flask/helpers.py';
    let baseVersion = 1;
    let oldText1 = 'def get_debug_flag():\n    val = os.environ.get("FLASK_DEBUG")';
    let newText1 = 'def get_debug_flag():\n    # Extended to support "off" and "n"\n    val = os.environ.get("FLASK_DEBUG")';
    let oldText2 = '    return val.lower() not in ("0", "false", "no")';
    let newText2 = '    return val.lower() not in ("0", "false", "no", "off", "n")';

    if (editor) {
      const doc = editor.document;
      baseVersion = doc.version;
      const workspaceFolder = vscode.workspace.workspaceFolders?.[0];
      if (workspaceFolder) {
        targetPath = vscode.workspace.asRelativePath(doc.uri);
      } else {
        targetPath = doc.fileName;
      }

      // If document has enough lines, pick real lines from the file
      if (doc.lineCount >= 4) {
        const line1 = doc.lineAt(0).text;
        const line2 = doc.lineAt(1).text;
        oldText1 = `${line1}\n${line2}`;
        newText1 = `${line1}\n// [ForgeTrail Mock Edit 1]\n${line2}`;

        const line3 = doc.lineAt(2).text;
        const line4 = doc.lineAt(3).text;
        oldText2 = `${line3}\n${line4}`;
        newText2 = `${line3}\n// [ForgeTrail Mock Edit 2]\n${line4}`;
      }
    }

    const runId = `mock-run-${Date.now()}`;

    const request1: ReviewRequest = {
      id: 'mock-hunk-1',
      runId,
      threadId: 'main',
      path: targetPath,
      kind: 'replace',
      oldText: oldText1,
      newText: newText1,
      startLine: 1,
      endLine: 4,
      reason: 'Add debug flag normalization for "off" and "n"',
      sources: ['src/flask/helpers.py', 'docs/config.rst'],
      index: 1,
      total: 3,
      baseVersion,
    };

    const request2: ReviewRequest = {
      id: 'mock-hunk-2',
      runId,
      threadId: 'main',
      path: targetPath,
      kind: 'replace',
      oldText: oldText2,
      newText: newText2,
      startLine: 5,
      endLine: 8,
      reason: 'Update docstring to list every value treated as false',
      sources: ['src/flask/helpers.py'],
      index: 2,
      total: 3,
      baseVersion,
    };

    const request3: ReviewRequest = {
      id: 'mock-hunk-3',
      runId,
      threadId: 'main',
      path: 'tests/test_mock_debug_flag.py',
      kind: 'create',
      oldText: '',
      newText: '# Auto-generated by ForgeTrail Mock Review\ndef test_debug_flag_off():\n    assert True\n',
      startLine: 1,
      endLine: 4,
      reason: 'Create unit test covering new false values',
      sources: ['tests/test_cli.py'],
      index: 3,
      total: 3,
      baseVersion: 1,
    };

    vscode.window.showInformationMessage('Starting ForgeTrail Mock Review (3 hunks)...');

    for (const req of [request1, request2, request3]) {
      const decision = await presenter.present(req);
      const feedbackStr = decision.feedback ? ` (feedback: "${decision.feedback}")` : '';
      vscode.window.showInformationMessage(
        `Hunk ${req.index}/${req.total} (${req.id}) was ${decision.decision.toUpperCase()}${feedbackStr}`
      );
    }

    vscode.window.showInformationMessage('ForgeTrail Mock Review completed.');
  });

  context.subscriptions.push(disposable);
}

